// Generates PWA icons + favicon (public/icons/*.png, public/favicon.ico)
// from the same mark as the header logo (src/app/layout.tsx Logo): three
// gradient equalizer bars, bottom-anchored like the 24×24 original.
// Run once: npm run icons
import sharp from "sharp";
import fs from "node:fs/promises";

// the header logo's geometry, scaled from its 24×24 viewBox to 512
const S = 512 / 24;
const LOGO_BARS = [
  { x: 4, y: 10, h: 7 }, // short-left
  { x: 10, y: 5, h: 14 }, // tall-middle (hangs 2px lower)
  { x: 16, y: 8, h: 9 }, // medium-right
];

function iconSvg({ rounded = true, barScale = 1.0 }) {
  const rx = rounded ? 6 * S : 0;
  // barScale shrinks the bars toward their common visual center (maskable
  // safe zone); positions are recomputed from the scaled group bbox.
  const group = {
    x0: 4 * S,
    x1: 19 * S,
    y0: 5 * S,
    y1: 19 * S,
  };
  const rects = LOGO_BARS.map(({ x, y, h }) => {
      const w = 3 * S * barScale;
      const hh = h * S * barScale;
      // scale the bar toward the group's center: anchored at the group's
      // top-left, shrunk by barScale, then re-centered by half the slack
      const px = group.x0 + (x * S - group.x0) * barScale + (group.x1 - group.x0) * (1 - barScale) / 2;
      const py = group.y0 + (y * S - group.y0) * barScale + (group.y1 - group.y0) * (1 - barScale) / 2;
      return `<rect x="${px.toFixed(1)}" y="${py.toFixed(1)}" width="${w.toFixed(
        1,
      )}" height="${hh.toFixed(1)}" rx="${(1.5 * S * barScale).toFixed(1)}" fill="url(#bars)"/>`;
    })
    .join("\n  ");
  return `<svg width="512" height="512" viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#0c4a6e"/>
      <stop offset="1" stop-color="#0f172a"/>
    </linearGradient>
    <linearGradient id="bars" x1="0" y1="1" x2="0" y2="0">
      <stop offset="0" stop-color="#38bdf8"/>
      <stop offset="1" stop-color="#a78bfa"/>
    </linearGradient>
  </defs>
  <rect width="512" height="512" rx="${rx}" fill="url(#bg)"/>
  ${rects}
</svg>`;
}

/** Wrap PNGs in a minimal .ico container (PNG-embedded entries). */
function ico(pngBuffers) {
  const n = pngBuffers.length;
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(n, 4);
  const dir = Buffer.alloc(16 * n);
  let offset = 6 + 16 * n;
  const parts = [header, dir];
  pngBuffers.forEach((png, i) => {
    dir.writeUInt8(png.dim, i * 16 + 0); // width (0 = 256)
    dir.writeUInt8(png.dim, i * 16 + 1); // height
    dir.writeUInt8(0, i * 16 + 2); // palette
    dir.writeUInt8(0, i * 16 + 3); // reserved
    dir.writeUInt16LE(1, i * 16 + 4); // color planes
    dir.writeUInt16LE(32, i * 16 + 6); // bits per pixel
    dir.writeUInt32LE(png.length, i * 16 + 8);
    dir.writeUInt32LE(offset, i * 16 + 12);
    offset += png.length;
    parts.push(png);
  });
  return Buffer.concat(parts);
}

await fs.mkdir("public/icons", { recursive: true });

const out = [
  ["icon-192.png", iconSvg({}), 192],
  ["icon-512.png", iconSvg({}), 512],
  ["icon-maskable-512.png", iconSvg({ rounded: false, barScale: 0.7 }), 512],
  ["apple-touch-icon.png", iconSvg({ rounded: false, barScale: 0.85 }), 180],
  ["favicon-32.png", iconSvg({}), 32],
];
for (const [name, svg, size] of out) {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(`public/icons/${name}`);
  console.log(`wrote public/icons/${name} (${size}x${size})`);
}

// multi-size favicon.ico (16 + 32 + 48 PNG entries). Written to the app
// router's file-convention location, which is the copy Next serves at
// /favicon.ico — one source of truth, regenerated by this script.
const png = async (size) => {
  const buf = await sharp(Buffer.from(iconSvg({}))).resize(size, size).png().toBuffer();
  buf.dim = size === 256 ? 0 : size;
  return buf;
};
const icoBuf = ico([await png(16), await png(32), await png(48)]);
await fs.writeFile("src/app/favicon.ico", icoBuf);
console.log(`wrote src/app/favicon.ico (${icoBuf.length} bytes)`);
